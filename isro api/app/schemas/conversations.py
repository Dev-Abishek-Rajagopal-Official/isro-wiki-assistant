"""Conversation, thread and run models."""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class ConversationCreate(BaseModel):
    title: str | None = Field(default=None, max_length=200,
                              description="Optional; generated by an LLM from the first question if omitted")


class ConversationUpdate(BaseModel):
    title: str | None = Field(default=None, min_length=1, max_length=200)
    archived: bool | None = None


class ThreadCreate(BaseModel):
    title: str | None = Field(default=None, max_length=200)


class ThreadUpdate(BaseModel):
    title: str | None = Field(default=None, min_length=1, max_length=200)
    archived: bool | None = None


class ThreadOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    conversation_id: uuid.UUID
    title: str | None
    archived: bool
    created_at: datetime
    updated_at: datetime
    last_run_at: datetime | None = None


class ConversationOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    title: str | None
    title_source: str | None
    archived: bool
    created_at: datetime
    updated_at: datetime
    last_activity_at: datetime | None = None
    thread_count: int = 0


class ConversationDetail(ConversationOut):
    threads: list[ThreadOut] = []


class ConversationPage(BaseModel):
    items: list[ConversationOut]
    next_cursor: str | None = Field(None, description="pass as ?cursor= to load the next page; null = no more")


class RunOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    thread_id: uuid.UUID
    question: str
    input_type: str
    transcript: dict | None = None
    status: str
    answer: str | None = None
    agents_used: list | None = None
    error: str | None = None
    started_at: datetime
    finished_at: datetime | None = None
    seconds: float | None = None
    llm_calls: int
    input_tokens: int
    output_tokens: int
    reasoning_tokens: int
    cached_tokens: int


class ThreadDetail(ThreadOut):
    messages: list[dict[str, Any]] = Field(default=[], description="conversation turns {type, content}")
    agent_state: dict[str, Any] = Field(default={}, description="current AgentState (from the checkpointer)")
    thread_usage: dict[str, Any] = {}
    runs: list[RunOut] = []


class AskRequest(BaseModel):
    question: str = Field(min_length=1, max_length=4000)
